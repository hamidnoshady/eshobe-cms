import { MigrateDownArgs, MigrateUpArgs, sql } from '@payloadcms/db-postgres'

/**
 * MCP: a key lifetime and an audit event for content changed by a key (#228).
 *
 * Two additive changes, both nullable/defaulted so an existing deployment keeps
 * working with no backfill:
 *
 *  - `payload_mcp_api_keys.expires_at` — the plugin ships no lifetime, so a key
 *    minted for a one-off integration stays valid forever. `mcpOverrideAuth` refuses
 *    an expired key; `NULL` means "no expiry", which is what every existing row is.
 *  - `mcp.contentChanged` on the three event enums. `src/plugins/mcpAudit.ts` writes
 *    it into `audit-log` for every MCP write; `webhooks.events` and
 *    `webhook-deliveries.event` share the vocabulary (`src/lib/saas/events.ts`) and
 *    would otherwise reject the value the audit row carries.
 *
 * `ADD VALUE IF NOT EXISTS` rather than a positional `BEFORE`: the repo's earlier
 * enum migrations use `BEFORE 'storage.changed'`, which makes a re-run a hard error
 * if the value is already present. Coupled with a `down` that cannot remove an enum
 * value (Postgres has no `DROP VALUE`), that leaves `up → down → up` broken. Here
 * `up` is idempotent, so a revert-and-reapply cycle converges; `down` drops the
 * column it added and says plainly that the enum label is left in place, which is
 * inert because nothing writes it once the code is reverted.
 *
 * Generated by hand on purpose: `payload migrate:create` at this commit also offers
 * unrelated page-builder enum drift that is not part of this change.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "payload_mcp_api_keys" ADD COLUMN IF NOT EXISTS "expires_at" timestamp(3) with time zone;

    ALTER TYPE "public"."enum_audit_log_action" ADD VALUE IF NOT EXISTS 'mcp.contentChanged';
    ALTER TYPE "public"."enum_webhooks_events" ADD VALUE IF NOT EXISTS 'mcp.contentChanged';
    ALTER TYPE "public"."enum_webhook_deliveries_event" ADD VALUE IF NOT EXISTS 'mcp.contentChanged';
  `)
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "payload_mcp_api_keys" DROP COLUMN IF EXISTS "expires_at";
  `)
}
