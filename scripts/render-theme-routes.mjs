#!/usr/bin/env node
/**
 * Render `theme-routes.caddy` from the CMS's own routing table.
 *
 * WAVE-11 §5 Option A: Caddy stays the edge for a site that adopted a deployable
 * theme, holding its certificate and keeping every `/api/*` carve-out pointed at
 * `web:3000`, while its *pages* proxy to the theme application. Caddy therefore
 * needs a host → upstream map, and a map a human maintains is one forgotten line
 * away from a customer's domain serving another customer's shop.
 *
 * Usage (on the deployment host, from cron or after a deploy):
 *
 *   CMS_URL=https://admin.example.com \
 *   PLATFORM_API_KEY=eshobe_live_… \
 *   node scripts/render-theme-routes.mjs /etc/caddy/theme-routes.caddy
 *
 * Then `caddy reload --config /etc/caddy/Caddyfile`. The script writes atomically and
 * exits non-zero without touching the file if the API is unreachable or answers
 * something unexpected — a routing table truncated by a transient 502 would take
 * every themed site offline at once, which is a far worse outcome than a stale one.
 */

import { writeFileSync, renameSync, readFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

const output = resolve(process.argv[2] ?? 'theme-routes.caddy')
const cmsUrl = (process.env.CMS_URL ?? '').replace(/\/+$/, '')
const apiKey = process.env.PLATFORM_API_KEY ?? ''

const die = (message) => {
  console.error(`render-theme-routes: ${message}`)
  process.exit(1)
}

if (!cmsUrl) die('CMS_URL is required.')
if (!apiKey) die('PLATFORM_API_KEY is required (a role: "platform" key).')

const HOST = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/i

let payload
try {
  const response = await fetch(`${cmsUrl}/api/platform/routing`, {
    headers: { accept: 'application/json', authorization: `Bearer ${apiKey}` },
    signal: AbortSignal.timeout(15_000),
  })
  if (!response.ok) die(`CMS answered ${response.status}.`)
  payload = await response.json()
} catch (error) {
  die(`could not reach the CMS: ${error.message}`)
}

if (!payload?.ok || !Array.isArray(payload.routes)) die('unexpected response shape.')

const lines = []
const seen = new Set()

for (const route of payload.routes) {
  const host = String(route?.host ?? '').toLowerCase()
  const upstream = String(route?.upstream ?? '').toLowerCase()

  // Both sides are validated here as well as in the CMS. This file becomes proxy
  // configuration on a machine terminating TLS for every customer; a malformed
  // hostname reaching it is either a Caddy that will not start or, worse, one that
  // starts with a rule nobody intended.
  if (!HOST.test(host) || !HOST.test(upstream)) {
    console.warn(`render-theme-routes: skipping malformed route ${host} → ${upstream}`)
    continue
  }
  if (seen.has(host)) {
    console.warn(`render-theme-routes: duplicate host ${host}, keeping the first`)
    continue
  }
  seen.add(host)
  lines.push(`\t${host} ${upstream}`)
}

const rendered = [
  '# Generated by scripts/render-theme-routes.mjs — do not edit by hand.',
  `# Source: ${cmsUrl}/api/platform/routing`,
  `# Generated at: ${payload.generatedAt ?? new Date().toISOString()}`,
  `# Routes: ${lines.length}`,
  '',
  'map {host} {theme_upstream} {',
  '\tdefault ""',
  ...lines,
  '}',
  '',
].join('\n')

if (existsSync(output) && readFileSync(output, 'utf8') === rendered) {
  console.log(`render-theme-routes: unchanged (${lines.length} routes)`)
  process.exit(0)
}

// Atomic: a half-written map read by a concurrent `caddy reload` is a config error
// on a machine serving every customer.
const temporary = `${output}.tmp-${process.pid}`
writeFileSync(temporary, rendered, 'utf8')
renameSync(temporary, output)

console.log(`render-theme-routes: wrote ${lines.length} routes to ${output} (${dirname(output)})`)
